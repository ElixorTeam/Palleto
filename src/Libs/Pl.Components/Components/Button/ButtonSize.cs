namespace Pl.Components.Components;

/// <summary>
/// Defines the size variant for a Button component.
/// </summary>
public enum ButtonSize
{
    /// <summary>
    /// Height: ~36px, Padding: 0.5rem horizontal.
    /// </summary>
    Small,

    /// <summary>
    /// Height: ~40px, Padding: 1rem horizontal.
    /// </summary>
    Default,

    /// <summary>
    /// Height: ~44px, Padding: 1.5rem horizontal.
    /// </summary>
    Large,

    /// <summary>
    /// Square: 40x40px (h-10 w-10).
    /// </summary>
    Icon,

    /// <summary>
    /// Square: 36x36px (h-9 w-9).
    /// </summary>
    IconSmall,

    /// <summary>
    /// Square: 44x44px (h-11 w-11).
    /// </summary>
    IconLarge
}